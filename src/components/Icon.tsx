export type IconKey = keyof typeof icons;

interface IconProps {
  name: IconKey;
  className?: string;
  size?: number | string;
  /** Provide a title only when the icon carries meaning on its own (otherwise it is hidden from screen readers). */
  title?: string;
}

export function Icon({ name, className, size, title }: IconProps) {
  const Cmp = icons[name];
  return <Cmp className={className} size={size} aria-hidden={title ? undefined : true} title={title} focusable="false" />;
}

export default Icon;
